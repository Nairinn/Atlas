import com.github.jengelman.gradle.plugins.shadow.tasks.ShadowJar
import com.google.protobuf.gradle.id

/*
 * The shared shape of every Atlas Kotlin service: JVM 21, protobuf
 * codegen from the repo-root proto/, grpc + grpc-kotlin generators, and
 * a shadow fat jar. A module applies this and then adds only its own
 * dependencies and mainClass.
 *
 * Artifact coordinates come from AtlasProtoArtifacts, generated from the
 * main version catalog (precompiled scripts cannot read `libs`).
 */

plugins {
    kotlin("jvm")
    id("com.google.protobuf")
    id("com.github.johnrengelman.shadow")
}

kotlin {
    jvmToolchain(21)
}

sourceSets {
    main {
        // Generated by protobuf-gradle-plugin under build/generated/source/proto/.
        // Adding them to the main source set lets Kotlin code import the
        // generated classes (atlas.*GrpcKt, atlas.events.*).
        java.srcDirs(
            "build/generated/source/proto/main/java",
            "build/generated/source/proto/main/grpc",
            "build/generated/source/proto/main/grpckt",
            "build/generated/source/proto/main/kotlin",
        )
        proto {
            // Pull .proto files from the repo-root /proto directory rather
            // than copying or symlinking them into the module. Symlinks
            // are fragile on Windows and copies drift.
            srcDir("$rootDir/proto")
        }
    }
}

protobuf {
    protoc {
        artifact = AtlasProtoArtifacts.PROTOC
    }
    plugins {
        id("grpc") {
            artifact = AtlasProtoArtifacts.GRPC_JAVA
        }
        id("grpckt") {
            // The :jdk8@jar classifier is the published artifact name for
            // the grpc-kotlin code generator; the plugin pulls a JAR rather
            // than a native binary so it works on any host.
            artifact = AtlasProtoArtifacts.GRPC_KOTLIN + ":jdk8@jar"
        }
    }
    generateProtoTasks {
        all().forEach { task ->
            task.plugins {
                id("grpc") {}
                id("grpckt") {}
            }
            task.builtins {
                id("kotlin") {}
            }
        }
    }
}

// Shadow jar produces a single fat JAR the Dockerfile can run with
// `java -jar app.jar`. The shaded grpc-netty already includes its own
// copy of Netty, so no extra relocations.
tasks.named<ShadowJar>("shadowJar") {
    archiveClassifier.set("all")
    archiveVersion.set("")
    mergeServiceFiles()
}
