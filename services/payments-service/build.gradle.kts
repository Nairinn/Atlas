// Atlas payments-service.
//
// Phase 4 scope (this commit):
//   - gRPC server on :50053 implementing atlas.payments.PaymentsService
//     (InitiateTransaction, SettleTransaction, GetWalletBalance,
//      RefundTransaction, DrainOutbox)
//   - grpc.health.v1.Health
//   - Wallet ledger + transactions (Exposed) with idempotency-key guard
//   - PaymentProvider abstraction (authorize/capture/refund); a fake provider
//     for local dev so Phase 4 stays at $0 spend
//   - Transactional outbox: every transaction state change writes a
//     protobuf FareEvent to payments.outbox in the SAME db tx, drained to
//     Kafka (atlas.fare.events) by a background dispatcher
//   - Ktor Netty HTTP server on :8053 serving /metrics (Micrometer/Prometheus)
//     and /webhooks/{provider} for async provider callbacks
//   - App.kt entry point + Dockerfile + shadow jar

