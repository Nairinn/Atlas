// Atlas auth-service.
//
// Phase 2A scope (done):
//   - Password hashing (bcrypt via jbcrypt)
//   - JWT signing and verification (HS256 via jose4j) with atlas:* claims
//   - User/session repositories (interface + in-memory + Exposed implementations)
//   - AuthService business logic: register, authenticate
//   - Unit tests
//
// Phase 2B scope (this commit):
//   - protoc + grpc-kotlin stub generation from repo-root proto/
//   - gRPC server on :50051 implementing atlas.auth.AuthService
//   - grpc.health.v1.Health
//   - 30s in-process token validation cache (Caffeine)
//   - Kafka producer for atlas.auth.tokens (protobuf-encoded AuthTokenEvent)
//   - Kafka consumer subscribed to its own topic for cache invalidation
//   - App.kt entry point + Dockerfile + shadow jar

import com.google.protobuf.gradle.id

plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.protobuf)
    alias(libs.plugins.shadow)
    application
}

kotlin {
    jvmToolchain(21)
}

application {
    mainClass.set("io.atlas.auth.AppKt")
}

sourceSets {
    main {
        // Generated by protobuf-gradle-plugin under build/generated/source/proto/.
        // Adding them to the main source set lets Kotlin code import the
        // generated classes (atlas.auth.AuthServiceGrpcKt, atlas.events.*).
        java.srcDirs(
            "build/generated/source/proto/main/java",
            "build/generated/source/proto/main/grpc",
            "build/generated/source/proto/main/grpckt",
            "build/generated/source/proto/main/kotlin",
        )
        proto {
            // Pull .proto files from the repo-root /proto directory rather than
            // copying or symlinking them into the module. Symlinks are fragile
            // on Windows and copies drift.
            srcDir("$rootDir/proto")
        }
    }
}

protobuf {
    protoc {
        artifact = libs.protoc.get().toString()
    }
    plugins {
        id("grpc") {
            artifact = libs.grpc.codegen.java.get().toString()
        }
        id("grpckt") {
            // The :jdk8@jar classifier is the published artifact name for the
            // grpc-kotlin code generator; the plugin pulls a JAR rather than
            // a native binary so it works on any host.
            artifact = libs.grpc.codegen.kotlin.get().toString() + ":jdk8@jar"
        }
    }
    generateProtoTasks {
        all().forEach { task ->
            task.plugins {
                id("grpc") {}
                id("grpckt") {}
            }
            task.builtins {
                id("kotlin") {}
            }
        }
    }
}

