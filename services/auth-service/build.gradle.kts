// Shadow jar produces a single fat JAR the Dockerfile can run with
// `java -jar app.jar`. The shaded grpc-netty already includes its own copy of
// Netty, so we don't need extra relocations.
tasks.shadowJar {
    archiveBaseName.set("auth-service")
    archiveClassifier.set("all")
    archiveVersion.set("")
    mergeServiceFiles()
}
